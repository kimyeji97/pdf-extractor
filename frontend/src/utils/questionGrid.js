/**
 * 문항 목록 열 수 산식 (REQ-D10)
 *
 * 패널 너비가 임계를 넘으면 열을 늘려 **문항 이미지 한 장의 폭이 임계를 넘지 않게** 한다.
 * 임계 이하에서는 1열이라 REQ-D01(대형 이미지)이 그대로 산다 — D10은 D01의 폐기가 아니라
 * 임계를 경계로 한 공존이다.
 *
 * 열 수는 **부모가 들고 있는 패널 너비 상태값**으로 계산한다. CSS `auto-fill`에 맡기면
 * 브라우저가 세는 폭이 패딩·스크롤바에 따라 달라져 같은 421px에서 OS마다 열 수가 갈린다.
 * 순수 함수라 "너비 X → 열 수 N"을 단위 테스트로 박을 수 있다(계획서 결정 "열 수 계산 주체").
 */

/**
 * 이미지 폭 상한(px). `ceil(너비 / 임계)`가 열 수다 — 상한 읽기.
 *
 * ⚠️ 작업 화면 section3의 **기본 너비 420과 같은 숫자지만 다른 상수다.** 기본 너비를 바꿔도
 * 임계는 따라가지 않는다 — 따라가면 "진입 직후 1열"이 우연에 기대게 된다. 두 값을 한 상수로
 * 묶지 말 것.
 */
export const QUESTION_COLUMN_THRESHOLD = 420;

/**
 * 패널 너비(px) → 열 수(정수, 최소 1).
 *
 * 420 → 1, 421 → 2, 800 → 2. 리사이즈 상한이 800이라 이 작업에서 3열은 나오지 않는다.
 */
export function columnsForWidth(width) {
  return Math.max(1, Math.ceil(width / QUESTION_COLUMN_THRESHOLD));
}
